"""Build docs/EVIDENCE.md: one file with the evidence for TraceGate (tasks, policy, tests, labels, judge validation, numbers).
Every number is read from a result file. Nothing is typed by hand.   Usage: python -m evals.evidence"""
import json
import subprocess
from collections import Counter
from pathlib import Path

from env import seed
from env.tools import PARAMS
